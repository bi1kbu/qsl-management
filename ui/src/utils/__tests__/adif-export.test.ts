import { describe, expect, it } from 'vitest'
import {
  buildAdiField,
  buildAdiContent,
  buildAdxApplicationField,
  buildAdxContent,
  buildAdxField,
  buildAdxTextField,
  resolveAdifModeFields,
} from '../adif-export'

describe('ADIF 3.1.7 导出', () => {
  it('ADI 只导出可打印 ASCII，并将换行压平', () => {
    expect(buildAdiField('COMMENT', 'Line 1\nLine 2')).toBe('<COMMENT:13>Line 1 Line 2')
    expect(buildAdiField('QTH', '北京 Beijing')).toBe('')
    expect(buildAdiField('MY_ANTENNA', '正V拉杆天线')).toBe('')
  })

  it('ADI 应用字段包含数据类型标识', () => {
    expect(buildAdiField('APP_QSLMS_RECORD_ID', 'QSO1091', 'S')).toBe(
      '<APP_QSLMS_RECORD_ID:7:S>QSO1091',
    )
  })

  it('ADI Header 以普通文本开头并以 EOH 结束', () => {
    const content = buildAdiContent(
      [{ name: 'ADIF_VER', value: '3.1.7' }],
      ['<CALL:6>BI1KBU <EOR>'],
    )
    expect(content.startsWith('Generated by QSL Management System\r\n')).toBe(true)
    expect(content).toContain('<ADIF_VER:5>3.1.7\r\n<EOH>')
    expect(content).toContain('<EOH>\r\n<CALL:6>BI1KBU <EOR>')
  })

  it('USB 和 LSB 导出为 SSB 子模式', () => {
    expect(resolveAdifModeFields('USB')).toEqual({ mode: 'SSB', submode: 'USB' })
    expect(resolveAdifModeFields(' lsb ')).toEqual({ mode: 'SSB', submode: 'LSB' })
    expect(resolveAdifModeFields('FT8')).toEqual({ mode: 'FT8', submode: '' })
  })

  it('ADX 使用国际化字段并转义 XML', () => {
    expect(buildAdxTextField('QTH', 'QTH_INTL', '日本大阪')).toBe('<QTH_INTL>日本大阪</QTH_INTL>')
    expect(buildAdxField('COMMENT', 'A & B < C')).toBe('<COMMENT>A &amp; B &lt; C</COMMENT>')
    expect(buildAdxApplicationField('qslms', 'record_id', 'QSO1091')).toBe(
      '<APP PROGRAMID="QSLMS" FIELDNAME="RECORD_ID" TYPE="S">QSO1091</APP>',
    )
  })

  it('ADX 文档包含标准 XML、Header 和 Records 结构', () => {
    const content = buildAdxContent(
      [
        { name: 'ADIF_VER', value: '3.1.7' },
        { name: 'PROGRAMID', value: 'QSL Management System' },
      ],
      [[buildAdxField('CALL', 'BI1KBU')]],
    )
    expect(content).toContain('<?xml version="1.0" encoding="UTF-8"?>')
    expect(content).toContain('<HEADER>')
    expect(content).toContain('<ADIF_VER>3.1.7</ADIF_VER>')
    expect(content).toContain('<RECORDS>')
    expect(content).toContain('<CALL>BI1KBU</CALL>')
  })
})
