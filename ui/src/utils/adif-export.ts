export interface AdifModeFields {
  mode: string
  submode: string
}

export interface AdxHeaderField {
  name: string
  value: string
}

export type AdiHeaderField = AdxHeaderField

export const normalizeAdifSingleLine = (value?: string): string => {
  return (value ?? '').trim().replace(/\r\n?|\n/g, ' ')
}

export const containsNonAscii = (value?: string): boolean => {
  return /[^\x20-\x7e]/.test(normalizeAdifSingleLine(value))
}

export const buildAdiField = (name: string, value?: string, dataType?: string): string => {
  const normalizedValue = normalizeAdifSingleLine(value)
  if (!normalizedValue || containsNonAscii(normalizedValue)) {
    return ''
  }
  const typeIndicator = dataType ? `:${dataType.toUpperCase()}` : ''
  return `<${name.toUpperCase()}:${normalizedValue.length}${typeIndicator}>${normalizedValue}`
}

export const buildAdiContent = (
  headerFields: AdiHeaderField[],
  records: string[],
  generator = 'QSL Management System',
): string => {
  const header = [
    `Generated by ${generator}`,
    ...headerFields.map((field) => buildAdiField(field.name, field.value)).filter(Boolean),
    '<EOH>',
  ].join('\r\n')
  return `${header}\r\n${records.join('\r\n')}\r\n`
}

export const resolveAdifModeFields = (value?: string): AdifModeFields => {
  const normalizedMode = (value ?? '').trim().toUpperCase().replace(/\s+/g, '')
  if (normalizedMode === 'USB' || normalizedMode === 'LSB') {
    return {
      mode: 'SSB',
      submode: normalizedMode,
    }
  }
  return {
    mode: normalizedMode,
    submode: '',
  }
}

const escapeXml = (value: string): string => {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;')
}

export const buildAdxField = (name: string, value?: string): string => {
  const normalizedValue = normalizeAdifSingleLine(value)
  if (!normalizedValue) {
    return ''
  }
  return `<${name.toUpperCase()}>${escapeXml(normalizedValue)}</${name.toUpperCase()}>`
}

export const buildAdxTextField = (name: string, intlName: string, value?: string): string => {
  return buildAdxField(containsNonAscii(value) ? intlName : name, value)
}

export const buildAdxApplicationField = (
  programId: string,
  fieldName: string,
  value?: string,
  dataType = 'S',
): string => {
  const normalizedValue = normalizeAdifSingleLine(value)
  if (!normalizedValue) {
    return ''
  }
  return `<APP PROGRAMID="${escapeXml(programId.toUpperCase())}" FIELDNAME="${escapeXml(fieldName.toUpperCase())}" TYPE="${escapeXml(dataType.toUpperCase())}">${escapeXml(normalizedValue)}</APP>`
}

export const buildAdxContent = (headerFields: AdxHeaderField[], records: string[][]): string => {
  const header = headerFields
    .map((field) => buildAdxField(field.name, field.value))
    .filter(Boolean)
    .map((field) => `    ${field}`)
    .join('\r\n')
  const recordContent = records
    .map((fields) => {
      const content = fields
        .filter(Boolean)
        .map((field) => `      ${field}`)
        .join('\r\n')
      return `    <RECORD>\r\n${content}\r\n    </RECORD>`
    })
    .join('\r\n')

  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<ADX>',
    '  <HEADER>',
    header,
    '  </HEADER>',
    '  <RECORDS>',
    recordContent,
    '  </RECORDS>',
    '</ADX>',
    '',
  ].join('\r\n')
}
